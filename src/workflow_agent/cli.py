"""Command line interface.

    python -m workflow_agent "Which products need restocking?"
    python -m workflow_agent --list
    python -m workflow_agent --validate
    python -m workflow_agent --run-examples          # runs examples/requests.yaml, writes outputs/
    python -m workflow_agent -i                      # interactive chat loop
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

from .engine import WorkflowAgent
from .render import render_run
from .settings import ROOT


def _json(state: dict) -> str:
    keep = ["request", "run_id", "mode", "route", "workflow_id", "workflow_name", "inputs", "trace", "status",
            "message", "answer", "result", "notes"]
    return json.dumps({k: state.get(k) for k in keep}, indent=2, default=str, ensure_ascii=False)


def run_examples(agent: WorkflowAgent, path: Path, out_dir: Path) -> int:
    examples = yaml.safe_load(path.read_text())
    out_dir.mkdir(parents=True, exist_ok=True)
    index = ["# Example runs", "", f"Mode: {agent.llm and 'LLM' or 'offline'} · generated by "
             "`python -m workflow_agent --run-examples`", "",
             "| # | Request | Expected | Selected | Status | Output |", "|---|---|---|---|---|---|"]
    mismatches = 0
    for n, ex in enumerate(examples, start=1):
        state = agent.run(ex["request"])
        slug = f"{n:02d}_{ex.get('expect') or 'none'}_{re.sub(r'[^a-z0-9]+', '_', ex.get('label', 'run').lower()).strip('_')}"
        (out_dir / f"{slug}.md").write_text(render_run(state) + "\n")
        (out_dir / f"{slug}.json").write_text(_json(state) + "\n")
        ok = state.get("workflow_id") == ex.get("expect")
        mismatches += not ok
        index.append(f"| {n} | {ex['request']} | {ex.get('expect') or '-'} | {state.get('workflow_id') or '-'}"
                     f"{'' if ok else ' ❌'} | {state.get('status')} | [{slug}.md]({slug}.md) |")
        print(f"[{'ok ' if ok else 'BAD'}] {ex['request'][:70]:70} -> {state.get('workflow_id')} ({state.get('status')})")
    (out_dir / "README.md").write_text("\n".join(index) + "\n")
    print(f"\nwrote {len(examples)} runs to {out_dir}  (routing mismatches: {mismatches})")
    return 1 if mismatches else 0


DECISION_KEYS = ("condition", "eligible_if", "flag_if", "required", "if_none", "checks", "cues", "where", "columns")


def write_docs(agent: WorkflowAgent, path: Path) -> None:
    """Generate docs/workflow_analysis.md from the registry so the analysis never drifts from the config."""
    from .tools import TOOLS

    out = ["# Workflow analysis", "",
           "_Generated by `python -m workflow_agent --docs` from the Excel file and `config/workflow_bindings.yaml`._", "",
           "For each workflow: input, required steps, tools/APIs, conditions/decisions and expected output, and how "
           "each Excel step is executed.", ""]
    for w in agent.registry.workflows.values():
        out += [f"## {w.id} · {w.name}", "",
                f"- **Trigger:** {w.trigger}",
                f"- **Input (Excel):** {w.inputs_text}",
                f"- **Inputs extracted from the request:** "
                + (", ".join(f"`{k}`" + (f" (default `{v.get('default')}`)" if v.get("default") is not None else "")
                             for k, v in w.inputs.items()) or "-"),
                f"- **Tools/APIs (Excel):** {', '.join(w.tools_required)}",
                f"- **Decision logic (Excel):** {w.decision_logic}",
                f"- **Expected output (Excel):** {w.expected_output}",
                f"- **Example request:** {'; '.join(f'_{e}_' for e in w.examples[:2])}", "",
                "| # | Excel step | Tool | What the tool does | Rule / condition |", "|---|---|---|---|---|"]
        for i, s in enumerate(w.steps, start=1):
            rules = []
            for k in DECISION_KEYS:
                if k in s.args and k != "columns":
                    rules.append(f"{k}: `{s.args[k]}`".replace("|", "\\|"))
            if isinstance(s.args.get("columns"), dict) and s.tool == "add_columns":
                rules += [f"`{c} = {e}`" for c, e in s.args["columns"].items()]
            if s.retries or s.on_error != "fail":
                rules.append(f"retries: {s.retries}, on_error: {s.on_error}" + (f" → `{s.fallback_tool}`" if s.fallback_tool else ""))
            tool = s.tool + (" (LLM + fallback)" if TOOLS[s.tool].uses_llm else "")
            out.append(f"| {i} | {s.label} | `{tool}` | {TOOLS[s.tool].description} | {'<br>'.join(rules) or '-'} |")
        out.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n")
    print("wrote", path)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="workflow_agent", description="Excel-driven AI workflow agent")
    p.add_argument("request", nargs="*", help="natural-language request")
    p.add_argument("--list", action="store_true", help="list workflows loaded from the Excel file")
    p.add_argument("--validate", action="store_true", help="check Excel and bindings are consistent")
    p.add_argument("--run-examples", nargs="?", const=str(ROOT / "examples" / "requests.yaml"), metavar="YAML")
    p.add_argument("--out", default=str(ROOT / "outputs"), help="output folder for --run-examples")
    p.add_argument("--json", action="store_true", help="print the full run state as JSON")
    p.add_argument("--offline", action="store_true", help="ignore any configured LLM")
    p.add_argument("-i", "--interactive", action="store_true")
    p.add_argument("--docs", nargs="?", const=str(ROOT / "docs" / "workflow_analysis.md"), metavar="MD",
                   help="generate the workflow analysis document")
    a = p.parse_args(argv)

    agent = WorkflowAgent(llm=None) if a.offline else WorkflowAgent()
    if a.list or a.validate:
        for w in agent.registry.workflows.values():
            mark = "✓" if w.executable else "✗"
            print(f"{mark} {w.id}  {w.name}  ({len(w.steps_text)} steps; tools: {', '.join(w.tools_required)})")
        for warn in agent.registry.warnings:
            print("  warning:", warn)
        if a.validate:
            bad = [w.id for w in agent.registry.workflows.values() if not w.executable]
            print("OK" if not bad else f"NOT EXECUTABLE: {bad}")
            return 1 if bad else 0
        return 0
    if a.docs:
        write_docs(agent, Path(a.docs))
        return 0
    if a.run_examples:
        return run_examples(agent, Path(a.run_examples), Path(a.out))
    if a.interactive:
        print("Type a request (empty line to quit).")
        while True:
            try:
                req = input("\n> ").strip()
            except EOFError:
                break
            if not req:
                break
            print(render_run(agent.run(req)))
        return 0
    if not a.request:
        p.print_help()
        return 2
    state = agent.run(" ".join(a.request))
    print(_json(state) if a.json else render_run(state))
    return 0


if __name__ == "__main__":
    sys.exit(main())
